/*
 * 训练 7：字节搬运不补 '\0'（read / memmove 的真相）
 *
 * 弱点来源：pingpong 里 rec[4] 读完直接 printf("%s") 越界打印垃圾；
 *          find 里 memmove 拷完要手动 p[DIRSIZ]=0。
 *          根因：read 和 memmove 是"字节搬运工"——拷多少字节就是多少，
 *          不负责给你补字符串结尾。这个实验让你亲眼看到后果。
 *
 * 任务：运行下面的程序（不需要改代码），先预测每一行输出，
 *       再看实际输出是否与预期一致；最后在文件末尾注释里
 *       用两句话回答：① 第 1 行的 '#' 从哪来？② 为什么第 2 行就干净了？
 */
#include <stdio.h>
#include <string.h>

int main(void)
{
    /* ---- 第 1 段：memmove 拷 5 字节，不补 '\0' ---- */
    char raw[5] = {'h', 'e', 'l', 'l', 'o'};   /* 注意：没有 '\0'！*/
    char buf[16];

    memset(buf, '#', 15);      /* buf[0..14] 全部填 '#' */
    buf[15] = 0;               /* 只在最后留一个 '\0' */

    memmove(buf, raw, 5);      /* 拷 5 字节：覆盖 buf[0..4]，buf[5] 还是 '#' */
    printf("1:[%s]\n", buf);   /* %s 会一路打到哪？*/

    /* ---- 第 2 段：手动补 '\0' 之后 ---- */
    buf[5] = 0;
    printf("2:[%s]\n", buf);

    /* ---- 第 3 段：strcpy vs memmove 拷同样内容，区别在"拷多少" ---- */
    char with_nul[] = {'h', 'i', '\0', 'x'};   /* 4 字节：中间有个 '\0' */
    char a[16], b[16];

    memset(a, '#', 16);
    memset(b, '#', 16);
    strcpy(a, with_nul);          /* 拷到 '\0' 停：只拷 h、i、'\0' 共 3 字节 */
    memmove(b, with_nul, 4);      /* 拷满 4 字节：h、i、'\0'、x */
    printf("3:[%s][%s]\n", a, b);               /* %s 视角两者相同 */
    printf("4: a[3]=%d, b[3]=%d  (#=%d, 'x'=%d)\n",
           a[3], b[3], '#', 'x'); /* 差异在 '\0' 之后：strcpy 没碰 a[3]，memmove 写了 b[3] */

    return 0;
}

